function applySwaps(text, lang) {
  if (lang === "fr" || !text) return text;
  let next = text;
  for (const [from, to] of swaps[lang]) {
    const pattern = new RegExp(from.replace(/[.*+?^${}()|[\]\\]/g, "\\$&"), "gi");
    next = next.replace(pattern, (match) => {
      const first = match.charAt(0);
      const latin = /^[A-Za-zÀ-ÿ]/.test(to);
      if (latin && first && first === first.toUpperCase() && first !== first.toLowerCase()) {
        return to.charAt(0).toUpperCase() + to.slice(1);
      }
      return to;
    });
  }
  if (lang === "ar") next = next.replace(/\bice\b/gi, "مثلج");
  return next;
}

const LanguageContext = createContext(null);

export function LanguageProvider({ children }) {
  const [lang, setLangState] = useState(() => localStorage.getItem(STORAGE_KEY) || "fr");

  useEffect(() => {
    localStorage.setItem(STORAGE_KEY, lang);
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
  }, [lang]);

  const api = useMemo(() => {
    function t(key, vars) {
      const template = copy[lang]?.[key] || copy.fr[key] || key;
      if (!vars) return template;
      return template.replace(/\{(\w+)\}/g, (_, name) => vars[name] ?? "");
    }
    function categoryLabel(id) {
      return categories[lang]?.[id]?.[0] || categories.fr[id]?.[0] || id;
    }
    function categoryBlurb(id) {
      return categories[lang]?.[id]?.[1] || categories.fr[id]?.[1] || "";
    }
    function text(value) {
      return applySwaps(value, lang);
    }
    function setLang(next) {
      setLangState(next);
    }
    return { lang, setLang, t, categoryLabel, categoryBlurb, text, dir: lang === "ar" ? "rtl" : "ltr" };
  }, [lang]);

  return <LanguageContext.Provider value={api}>{children}</LanguageContext.Provider>;
}

export function useI18n() {
  return useContext(LanguageContext);
}
